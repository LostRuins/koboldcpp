bool is_cantonese_language(std::string_view language) noexcept {
    std::string lang = to_lower_ascii(trim_ascii(language));
    if (lang.empty() || lang == "auto") {
        return false;
    }
    // Normalize separators to '-'
    for (char & ch : lang) {
        if (ch == '_') {
            ch = '-';
        }
    }
    // Direct tags
    if (lang == "yue" || lang == "yue-hant" || lang == "yue-hans" ||
        lang == "zh-yue" || lang == "zh-hk" || lang == "zh-mo" ||
        lang == "zh-hant-hk" || lang == "zh-hant-mo" ||
        lang == "cantonese") {
        return true;
    }
    // Substring heuristics: any "yue" or "cantonese" or "hk"/"mo" as cantonese region
    if (lang.find("yue") != std::string::npos) {
        return true;
    }
    if (lang.find("cantonese") != std::string::npos) {
        return true;
    }
    // zh-Hant alone is not necessarily Cantonese (Taiwan also uses Hant),
    // so only hk/mo are treated as Cantonese.
    if (lang == "hk" || lang == "mo" || lang == "zh-hant") {
        // zh-Hant without region is ambiguous (Taiwan uses Hant for Mandarin),
        // so do NOT treat as Cantonese to avoid false positives.
        // Only hk/mo are Cantonese.
        return false;
    }
    return false;
}

bool contains_traditional_characters(std::string_view text) {
    const auto & map = t2s_map();
    auto cps = decode_utf8_strict(text, "chinese variant text");
    for (uint32_t cp : cps) {
        if (map.find(cp) != map.end()) {
            return true;
        }
    }
    return false;
}

std::string convert_traditional_to_simplified(std::string_view text) {
    const auto & map = t2s_map();
    auto cps = decode_utf8_strict(text, "chinese variant text");
    bool changed = false;
    for (uint32_t & cp : cps) {
        auto it = map.find(cp);
        if (it != map.end()) {
            cp = it->second;
            changed = true;
        }
    }
    if (!changed) {
        return std::string(text);
    }
    return encode_utf8_codepoints(cps);
}

std::string maybe_convert_traditional_to_simplified(
    std::string_view text,
    std::string_view language) {
    if (is_cantonese_language(language)) {
        // Keep Traditional for Cantonese
        return std::string(text);
    }
    return convert_traditional_to_simplified(text);
}



